"""Derive the orchestrated-execution numbers the paper reports from the frozen batch witness.

The batch runner brings up each campaign's SUT, configures its declared vulnerabilities, executes
its techniques, and tears the environment down, recording one record per campaign. This reads the
frozen witness and writes LaTeX macros, so no execution number is hand-typed. Status-success counts
steps that ran to completion, matching the bar reported by prior Docker-based emulation; adapted
counts the subset backed by mechanical evidence; inspired counts steps recorded as conceptual
markers where the substrate cannot honestly execute the technique.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from evaluation.replay_audit import RecordedStep, audit_replay_report

WITNESS = PROJECT_ROOT / "release" / "runs" / "orchestrated" / "witness" / "corpus_batch.json"
OUTPUT = PROJECT_ROOT / "release" / "orchestrated_batch_macros.tex"


def macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def successful_execution_steps(record: dict) -> tuple[RecordedStep, ...]:
    manifest = json.loads(
        (PROJECT_ROOT / record["evidence_manifest"]).read_text(encoding="utf-8")
    )
    steps = tuple(
        RecordedStep.model_validate({
            key: step[key] for key in RecordedStep.model_fields
        }) for step in manifest["techniques"]
    )
    return tuple(
        step for step in steps
        if step.status == "success"
        and step.executed_mode != "naive_simulated"
        and step.evidence_files
    )


def main() -> int:
    audit = audit_replay_report(WITNESS, PROJECT_ROOT)
    for record in audit.records:
        blocking = set(record.issues) - {"inspired_steps_counted_as_execution"}
        if blocking:
            raise ValueError(f"{record.campaign_id}: {sorted(blocking)}")
    records = json.loads(WITNESS.read_text(encoding="utf-8"))
    executions = [successful_execution_steps(record) for record in records]
    campaigns = len(records)
    total = sum(record["total"] for record in records)
    status_success = sum(record["successful"] for record in records)
    evidence_backed = sum(len(steps) for steps in executions)
    adapted = sum(
        step.executed_fidelity == "adapted"
        for steps in executions for step in steps
    )
    inspired_executions = sum(
        step.executed_fidelity == "inspired"
        for steps in executions for step in steps
    )
    inspired = sum(record["marker_only_successful"] for record in records)
    clean = sum(1 for record in records if record["final_namespace_clean"])
    fully_adapted = sum(
        len(steps) == record["total"]
        and all(step.executed_fidelity == "adapted" for step in steps)
        for record, steps in zip(records, executions, strict=True)
    )
    lines = [
        "% Generated by scripts/build_orchestrated_batch_values.py from the frozen batch witness.",
        macro("batchCampaigns", str(campaigns)),
        macro("batchSteps", str(total)),
        macro("batchStatusSuccess", str(status_success)),
        macro("batchAdapted", str(adapted)),
        macro("batchEvidenceBacked", str(evidence_backed)),
        macro("batchInspiredExecutions", str(inspired_executions)),
        macro("batchInspired", str(inspired)),
        macro("batchCleanTeardown", f"{clean}/{campaigns}"),
        macro("batchFullyAdaptedCount", str(fully_adapted)),
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")
    for line in lines[1:]:
        print("  " + line)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
