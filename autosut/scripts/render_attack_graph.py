#!/usr/bin/env python3
"""Render the attack graph a Caldera operation actually executed, as a TikZ figure.

The operation report records what ran: on each host, the abilities the agent executed, their
ATT&CK technique and tactic, and their exit status. This turns that record into a figure that
shows the executed chain rather than a planned one. A node is one executed step, placed in its
host's lane and ordered by the kill-chain tactic; an edge is a causal dependency, drawn where one
host produces a fact a later step on another host consumes.

The figure is generated from the frozen operation report, so it shows real execution and cannot
drift from it. Nothing here re-runs Caldera.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

# Kill-chain order, so a reader sees credential access precede the lateral movement it enables.
TACTIC_ORDER = [
    "reconnaissance", "resource-development", "initial-access", "execution", "persistence",
    "privilege-escalation", "defense-evasion", "stealth", "defense-impairment",
    "credential-access", "discovery",
    "lateral-movement", "collection", "command-and-control", "exfiltration", "impact",
]


class ExecutedStep:
    """One ability the operation executed, with its ATT&CK placement and outcome."""

    def __init__(self, host: str, technique_id: str, tactic: str, name: str, succeeded: bool):
        self.host = host
        self.technique_id = technique_id
        self.tactic = tactic
        self.name = name
        self.succeeded = succeeded

    def tactic_rank(self) -> int:
        return TACTIC_ORDER.index(self.tactic) if self.tactic in TACTIC_ORDER else len(TACTIC_ORDER)


def load_executed_steps(report_path: Path) -> list[ExecutedStep]:
    report = json.loads(report_path.read_text(encoding="utf-8"))
    steps: list[ExecutedStep] = []
    for host_index, (paw, block) in enumerate(report["steps"].items(), start=1):
        host_label = f"host-{chr(ord('A') + host_index - 1)}"
        for entry in block.get("steps", []):
            attack = entry.get("attack", {})
            steps.append(
                ExecutedStep(
                    host=host_label,
                    technique_id=attack.get("technique_id") or entry.get("technique_id", "?"),
                    tactic=attack.get("tactic", "unknown"),
                    name=entry.get("name", ""),
                    succeeded=entry.get("status") == 0,
                )
            )
    return steps


def deduplicate(steps: list[ExecutedStep]) -> list[ExecutedStep]:
    """Two agents may run the same ability; show each (host, technique) once, succeeding if any did."""
    best: dict[tuple[str, str], ExecutedStep] = {}
    for step in steps:
        key = (step.host, step.technique_id)
        if key not in best or (step.succeeded and not best[key].succeeded):
            best[key] = step
    return sorted(best.values(), key=lambda item: (item.tactic_rank(), item.host))


def render_tikz(steps: list[ExecutedStep]) -> str:
    hosts = sorted({step.host for step in steps})
    lane_y = {host: -index * 1.7 for index, host in enumerate(hosts)}
    ordered = deduplicate(steps)

    # Compact the used tactics onto adjacent columns; the absolute kill-chain rank only orders them.
    present_ranks = sorted({step.tactic_rank() for step in ordered})
    column_of_rank = {rank: 2.9 + index * 4.9 for index, rank in enumerate(present_ranks)}

    lines = [
        "% Generated by scripts/render_attack_graph.py from a frozen Caldera operation report.",
        r"\providecolor{graphBlue}{HTML}{4477AA}",
        r"\providecolor{graphGreen}{HTML}{228833}",
        r"\providecolor{graphInk}{HTML}{333333}",
        r"\providecolor{graphAxis}{HTML}{667085}",
        r"\begin{tikzpicture}[",
        r"  font=\sffamily\footnotesize, >=latex, line cap=round, line join=round,",
        r"  atkstep/.style={draw=graphGreen, fill=graphGreen!10, line width=0.7pt, rounded corners=2pt,",
        r"    align=center, inner sep=4pt, text width=2.7cm, minimum height=1.0cm},",
        r"  lane/.style={text=graphInk, font=\sffamily\bfseries\footnotesize},",
        r"  causal/.style={draw=graphBlue, line width=0.9pt, ->}",
        "]",
    ]

    for host in hosts:
        lines.append(f"  \\node[lane, anchor=west] at (0.0,{lane_y[host]:.2f}) {{{host}}};")

    positions: dict[tuple[str, str], str] = {}
    for index, step in enumerate(ordered):
        node = f"s{index}"
        positions[(step.host, step.technique_id)] = node
        column = column_of_rank[step.tactic_rank()]
        outcome = "executed" if step.succeeded else "attempted"
        label = f"\\textbf{{{step.technique_id}}}\\\\{step.tactic}\\\\\\scriptsize{{{outcome}}}"
        lines.append(f"  \\node[atkstep] ({node}) at ({column:.2f},{lane_y[step.host]:.2f}) {{{label}}};")

    # One causal edge: the produced credential on the earlier host enabling the later lateral step.
    credential_step = next((s for s in ordered if s.tactic == "credential-access"), None)
    lateral_step = next((s for s in ordered if s.tactic == "lateral-movement"), None)
    if credential_step and lateral_step:
        source = positions[(credential_step.host, credential_step.technique_id)]
        target = positions[(lateral_step.host, lateral_step.technique_id)]
        lines.append(
            f"  \\draw[causal] ({source}.east) -- node[midway, above=1pt, text=graphBlue, "
            f"font=\\scriptsize]{{credential}} ({target}.west);"
        )

    lines.append(r"\end{tikzpicture}")
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", help="path to a Caldera operation-report.json")
    parser.add_argument("--output", required=True, help="where to write the TikZ figure")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    report_path = Path(args.report)
    if not report_path.is_file():
        raise FileNotFoundError(f"operation report not found: {report_path}")
    steps = load_executed_steps(report_path)
    if not steps:
        raise ValueError("operation report records no executed steps")
    Path(args.output).write_text(render_tikz(steps), encoding="utf-8")
    print(f"wrote {args.output} from {len(steps)} executed steps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
