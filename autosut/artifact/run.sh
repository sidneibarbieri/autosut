#!/bin/bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

usage() {
  cat <<'EOF'
Usage:
  bash artifact/run.sh [--help] [--image-lock FILE]

Runs two controlled AutoSUT replay campaigns and records the generated evidence.
This command requires Docker. Review mode may pull or build images.
--image-lock verifies preloaded identities and forbids image pull/build.
Use --help to inspect it without contacting Docker or changing experiment state.
EOF
}

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  usage
  exit 0
fi
image_lock="${AUTOSUT_DOCKER_IMAGE_LOCK:-}"
if [[ $# -eq 2 && "$1" == "--image-lock" ]]; then
  image_lock="$2"
elif [[ $# -ne 0 ]]; then
  usage >&2
  exit 2
fi
if [[ -n "$image_lock" && "$image_lock" != /* ]]; then
  image_lock="$PWD/$image_lock"
fi

cd "$ROOT_DIR"
source "$ROOT_DIR/scripts/python_env.sh"
PYTHON_BIN="$(autosut_resolve_python "$ROOT_DIR" "$ROOT_DIR/requirements-reviewer.txt")"

export PYTHONPATH="$ROOT_DIR/src${PYTHONPATH:+:$PYTHONPATH}"

fail() {
  printf '[artifact/run][FAIL] %s\n' "$*" >&2
  exit 1
}

if ! command -v docker >/dev/null 2>&1; then
  fail "Docker is required for the controlled replays but was not found on PATH"
fi

if ! docker_version="$(docker info --format '{{.ServerVersion}}' 2>&1)"; then
  printf '%s\n' "$docker_version" >&2
  fail "Docker is installed, but its daemon is not reachable"
fi
echo "[artifact/run] Docker daemon: $docker_version"

if [[ -n "$image_lock" ]]; then
  "$PYTHON_BIN" scripts/docker_image_lock.py verify --lock "$image_lock" \
    --campaign 0.c0017 --campaign 0.shadowray
else
  target_image="python:3.11-slim"
  if ! docker image inspect "$target_image" >/dev/null 2>&1; then
    echo "[artifact/run] pulling target image $target_image..."
    docker pull "$target_image" || fail "could not pull target image $target_image"
  fi

  attacker_image="autosut/dmz-host:s28"
  attacker_dockerfile="$ROOT_DIR/.docker/dmz-host/Dockerfile"
  if ! docker image inspect "$attacker_image" >/dev/null 2>&1; then
    [[ -f "$attacker_dockerfile" ]] || fail \
      "missing attacker image $attacker_image and build recipe $attacker_dockerfile"
    echo "[artifact/run] building attacker image $attacker_image..."
    docker build \
      -t "$attacker_image" \
      -f "$attacker_dockerfile" \
      "$(dirname "$attacker_dockerfile")" \
      || fail "could not build attacker image $attacker_image"
  fi

fi

run_campaign() {
  if [[ -n "$image_lock" ]]; then
    "$PYTHON_BIN" scripts/run_orchestrated_campaign.py "$@" --docker-image-lock "$image_lock"
  else
    "$PYTHON_BIN" scripts/run_orchestrated_campaign.py "$@"
  fi
}

echo "[artifact/run] executing infrastructure smoke campaign..."
run_campaign 0.c0017

echo "[artifact/run] executing state-contract campaign..."
run_campaign 0.shadowray --fidelity surrogate

# Bind validation to exactly the two bundles generated by this invocation.
# Timestamp inference is unsafe: an old checkout can have a released golden
# run whose name happens to sort after a reviewer run.
reviewer_runs_dir="release/evidence/_reviewer_runs"
mkdir -p "$reviewer_runs_dir"
"$PYTHON_BIN" - <<'PY'
import json
from pathlib import Path

root = Path("release/evidence")
runs = {}
for campaign in ("0.c0017", "0.shadowray"):
    candidates = [path for path in root.glob(f"{campaign}_*") if path.is_dir()]
    if not candidates:
        raise SystemExit(f"missing reviewer-generated evidence for {campaign}")
    runs[campaign] = max(candidates, key=lambda path: path.stat().st_mtime_ns).as_posix()

Path("release/evidence/_reviewer_runs/latest-smoke-session.json").write_text(
    json.dumps({"campaign_runs": runs}, indent=2) + "\n",
    encoding="utf-8",
)
PY

echo "[artifact/run] done"
